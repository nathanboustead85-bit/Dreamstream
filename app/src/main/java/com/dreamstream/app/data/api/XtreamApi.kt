interface XtreamApi {

    @GET("player_api.php")
    suspend fun getLiveCategories(
        @Query("username") username: String,
        @Query("password") password: String,
        @Query("action") action: String =
            "get_live_categories"
    ): List<LiveCategory>

    @GET("player_api.php")
    suspend fun getVodCategories(
        @Query("username") username: String,
        @Query("password") password: String,
        @Query("action") action: String =
            "get_vod_categories"
    ): List<VodCategory>

    @GET("player_api.php")
    suspend fun getSeriesCategories(
        @Query("username") username: String,
        @Query("password") password: String,
        @Query("action") action: String =
            "get_series_categories"
    ): List<SeriesCategory>
}
